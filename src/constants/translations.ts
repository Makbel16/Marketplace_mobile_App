/**
 * Formats a number as Ethiopian Birr (ETB / ብር)
 * e.g. 100 ETB / 100 ብር
 */
export const formatCurrency = (amount: number, language: Language = 'en'): string => {
  const formattedNumber = Math.round(amount).toLocaleString();
  if (language === 'am') {
    return `${formattedNumber} ብር`;
  }
  return `${formattedNumber} ETB`;
};

